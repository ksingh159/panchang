def region_for_place(place, lat=None, lon=None):
    """The region key for a place name, else the nearest region when the point lies in India, else None."""
    text = (place or "").lower()
    for key, hints in PLACE_HINTS.items():
        if any(h in text for h in hints):
            return key
    if lat is not None and lon is not None and 6 <= lat <= 37.5 and 68 <= lon <= 97.5:
        return min(REGION_CENTRES, key=lambda k: (REGION_CENTRES[k][0] - lat) ** 2 + (REGION_CENTRES[k][1] - lon) ** 2)
    return None
