_VOWEL_FAMILY = {"आ": "अ", "ई": "इ", "ऊ": "उ", "ऐ": "ए", "औ": "ओ"}
_MATRA_FAMILY = {"ा": "", "ी": "ि", "ू": "ु", "ै": "े", "ौ": "ो", "ृ": "ि"}
_CONSONANT_FAMILY = {"ष": "श", "ब": "व"}
VIRAMA = "्"
NUKTA = "़"
MATRAS = set("ािीुूृेैोौ")


def akshara_key(text):
    """The sound family of the first akshara (see the module notes), or None for an empty name."""
    if not text:
        return None
    first = text[0]
    if first in "ऋॠ":
        return "रि"
    if "अ" <= first <= "औ":
        return _VOWEL_FAMILY.get(first, first)
    c = _CONSONANT_FAMILY.get(first, first)
    i = 1
    while i < len(text) and text[i] in (NUKTA, VIRAMA):   # skip a nukta and every consonant of a conjunct
        i += 2 if text[i] == VIRAMA else 1
    nxt = text[i] if i < len(text) else ""
    vowel = _MATRA_FAMILY.get(nxt, nxt) if nxt in MATRAS else ""
    if c == "श" and vowel:
        c = "स"
    return c + vowel


def is_loose(text):
    """True when the name's letter is a matter of family custom (conjunct, ऋ/कृ, ब, श with a vowel)."""
    if not text:
        return False
    second = text[2:3] if text[1:2] == NUKTA else text[1:2]
    return text[0] in "ऋॠबश" or second in (VIRAMA, "ृ")


def names_for(syllables, gender="", loose=False):
    """Names whose first sound is one of ``syllables``; ``loose`` also matches on the first consonant alone."""
    keys = {akshara_key(s) for s in syllables}
    keys.discard(None)
    heads = {k[0] for k in keys}

    def hit(key):
        return key in keys or (loose and key and key[0] in heads)

    out = [dict(deva=n[0], roman=n[1], gender=n[2], meaning=n[3], letter=akshara_key(n[0]), custom=is_loose(n[0]))
           for n in NAMES if hit(akshara_key(n[0])) and (not gender or n[2] == gender)]
    return out


def syllables(nak_index):
    return NAKSHATRAS[nak_index][3].split()


def rashi_letters(rashi_index):
    """The nine pada syllables that fall in a rashi."""
    letters = []
    for pada in range(rashi_index * 9, rashi_index * 9 + 9):
        nak, p = divmod(pada, 4)
        letters.append((NAKSHATRAS[nak][3].split()[p], NAKSHATRAS[nak][4].split()[p]))
    return letters


def reading(moon_lon, gender=""):
    """Everything the page shows for a sidereal Moon longitude."""
    span = 360 / 27
    nak = int(moon_lon // span) % 27
    pada = int((moon_lon % span) // (span / 4))
    rashi = int(moon_lon // 30) % 12
    en, hi, deity, deva, roman = NAKSHATRAS[nak]
    letter = deva.split()[pada]
    main = names_for([letter], gender)
    rashi_set = rashi_letters(rashi)
    more = [n for n in names_for([d for d, _ in rashi_set], gender, loose=True)
            if n["deva"] not in {m["deva"] for m in main}]
    return {
        "nak_index": nak, "nakshatra": en, "nakshatra_hi": hi, "deity": deity, "pada": pada + 1,
        "letter": letter, "letter_roman": roman.split()[pada], "pada_letters": list(zip(deva.split(), roman.split())),
        "rashi": RASHIS[rashi], "rashi_letters": rashi_set, "names": main, "more_names": more,
    }


def namakarana_days(birth_date, panchang_for_day, days=range(11, 21)):
    """
    Days after birth with their tithi, nakshatra and weekday, and whether each suits the naming.
    ``panchang_for_day(date)`` returns a get_panchang dict for that morning.
    """
    from datetime import timedelta
    from .aahaar import tithi_number
    out = []
    for n in days:
        d = birth_date + timedelta(days=n - 1)   # the birth day is day 1
        p = panchang_for_day(d) or {}
        weekday = d.strftime("%A")
        tithi = p.get("paksha_tithi", "")
        tn = tithi_number(tithi)
        nak = (p.get("nakshatra") or "").split(" (")[0].split(" Pada")[0].strip()
        reasons = []
        if weekday not in GOOD_WEEKDAYS:
            reasons.append(f"{weekday} is not preferred")
        if tn in RIKTA or "Amavasya" in tithi:
            reasons.append("Rikta tithi" if tn in RIKTA else "Amavasya")
        if nak and nak not in GOOD_NAKSHATRAS:
            reasons.append(f"{nak} nakshatra is not among the preferred")
        out.append({"day": n, "date": d, "weekday": weekday, "tithi": tithi, "nakshatra": nak,
                    "good": not reasons, "reasons": reasons})
    return out
